"""
app/services/blackbox/build_risk_probes.py
==========================================
Build-risk probe set — conditional, budget-aware, 16 checks.

Zero hardcoded probes in the main path. Every probe is generated by
synthesize_build_risk_probes() which calls Groq with check specifications.
The static BUILD_RISK_CHECKS list defines WHAT to test (spec), not the actual
prompt text — Groq writes those from the spec + system context.

A minimal static fallback prompt is carried per check only for Groq-down mode;
it is always tagged source="fallback" and forces confidence="low".

Conditionality
--------------
Checks are conditional on the registration profile:
  always          — run for any AI-generated system
  needs_actions   — only when autonomous_actions declared
  needs_agentic   — only when an agentic tool (Cursor, Claude Code, etc.) declared
  needs_tools     — only when real_time_data or tool access declared

The 16 checks cover everything from the build-risk methodology:
  Group 1 — Leaks it shouldn't      (instruction_leak, secret_leak, raw_error_leak)
  Group 2 — Injection flaws         (sql_injection, command_injection, template_injection, nosql_injection)
  Group 3 — Authorization           (idor_authz)
  Group 4 — Web security config     (web_security_config, csrf_missing, ssrf)
  Group 5 — Output encoding         (output_encoding)
  Group 6 — Input handling          (input_robustness, rate_limiting)
  Group 7 — Dependency/supply chain (dependency_risk)
  Group 8 — Agentic config          (config_file_poisoning)
  Group 9 — Persona stability       (persona_stability)

Budget allocation
-----------------
Each check gets floor(budget / active_checks) probes (min 1).
The static fallback emits exactly 1 probe per check when Groq is unavailable.
"""

